export function resolveUiLang(code) {
  const c = String(code || 'en').trim().toLowerCase();
  return TRANSLATIONS[c] ? c : 'en';
}

export function t(langCode, key, vars = {}) {
  const dict = TRANSLATIONS[resolveUiLang(langCode)] || TRANSLATIONS.en;
  let str = dict[key] ?? TRANSLATIONS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replaceAll(`{${k}}`, String(v ?? ''));
  }
  return str;
}
