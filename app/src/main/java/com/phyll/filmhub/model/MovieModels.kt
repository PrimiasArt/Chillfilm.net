package com.phyll.filmhub.model

enum class CountryCategory(
    val code: String,
    val displayName: String,
    val flagEmoji: String
) {
    ALL("all", "Mới & Hot", "🔥"),
    YOUTUBE("yt", "YouTube Phim", "▶️"),
    THAILAND("th", "Thái Lan", "🇹🇭"),
    KOREA("kr", "Hàn Quốc", "🇰🇷"),
    CHINA("cn", "Trung Quốc", "🇨🇳"),
    USA("us", "Âu Mỹ", "🇺🇸"),
    UK("uk", "Anh Quốc", "🇬🇧"),
    JAPAN("jp", "Nhật Bản", "🇯🇵"),
    GLOBAL("global", "Phim Lẻ Mới", "🎬"),
    LIVE_TV("live", "Phim Bộ Mới", "📺");

    companion object {
        fun fromSlugOrName(raw: String): CountryCategory {
            val normalized = raw.lowercase().trim()
            return when {
                normalized.contains("youtube") || normalized == "yt" -> YOUTUBE
                normalized.contains("thái") || normalized.contains("thai") || normalized == "th" -> THAILAND
                normalized.contains("hàn") || normalized.contains("han-quoc") || normalized.contains("korea") || normalized == "kr" -> KOREA
                normalized.contains("trung") || normalized.contains("china") || normalized.contains("hong kong") || normalized.contains("đài loan") || normalized == "cn" -> CHINA
                normalized.contains("nhật") || normalized.contains("nhat-ban") || normalized.contains("japan") || normalized == "jp" -> JAPAN
                normalized.contains("anh") || normalized.contains("uk") || normalized.contains("british") || normalized == "gb" -> UK
                normalized.contains("mỹ") || normalized.contains("au-my") || normalized.contains("usa") || normalized == "us" -> USA
                else -> GLOBAL
            }
        }
    }
}

enum class ContentType {
    MOVIE,
    SERIES,
    LIVE_CHANNEL
}

data class ExternalSubtitleRef(
    val id: String,
    val label: String,
    val languageCode: String, // e.g., "th", "vi", "en", "zh", "ko", "und"
    val urlOrContent: String,
    val isRawContent: Boolean = false,
    val sourcePlatform: String = "OpenSubtitles",
    val isAutoGenerated: Boolean = false
) {
    val isThai: Boolean
        get() {
            val code = languageCode.lowercase()
            val lbl = label.lowercase()
            return code == "th" || code == "tha" || code.startsWith("th-") ||
                lbl.contains("thai") || lbl.contains("ไทย") || lbl.contains("thái")
        }
}

data class Episode(
    val id: String,
    val name: String,
    val streamUrl: String,
    val audioStreamUrl: String = "",
    val fallbackStreamUrl: String = "",
    val headers: Map<String, String> = emptyMap(),
    val subtitles: List<ExternalSubtitleRef> = emptyList()
)

data class ServerGroup(
    val serverName: String,
    val episodes: List<Episode>
)

data class MovieItem(
    val id: String,
    val title: String,
    val originalTitle: String = "",
    val year: String = "",
    val country: CountryCategory = CountryCategory.GLOBAL,
    val genre: String = "Điện ảnh",
    val duration: String = "",
    val quality: String = "FHD",
    val posterUrl: String = "",
    val backdropUrl: String = "",
    val description: String = "",
    val contentType: ContentType = ContentType.MOVIE,
    val providerId: String = "modern_vod",
    val providerName: String = "Phyll Cinema",
    val hasNativeThaiSub: Boolean = false,
    val imdbId: String = "",
    val servers: List<ServerGroup> = emptyList(),
    val detailLookupId: String? = null
) {
    val firstPlayableEpisode: Episode?
        get() = servers.firstOrNull()?.episodes?.firstOrNull()
}

data class WatchProgress(
    val movieId: String,
    val title: String,
    val posterUrl: String,
    val countryCode: String,
    val streamUrl: String,
    val episodeId: String,
    val episodeName: String,
    val positionMs: Long,
    val durationMs: Long,
    val updatedAt: Long = System.currentTimeMillis()
) {
    val progressFraction: Float
        get() = if (durationMs > 0L) (positionMs.toFloat() / durationMs.toFloat()).coerceIn(0f, 1f) else 0f
}

